// KAIROS for Android — Developed by RC. Port of kairos/skills (SkillManager + sandboxed runner).
//
// Desktop skills are Python classes run in a subprocess that can only reach a whitelisted
// set of engine methods over RPC. Android cannot run CPython, so skills here are JavaScript
// files run in Mozilla Rhino (MPL-2.0, pure Java) with the same contract:
//   - no Java access (safe standard objects + a ClassShutter that denies every class),
//   - no file, network or secret access except through the whitelisted `kairos` RPC object,
//   - a hard time limit enforced by Rhino's instruction observer, and a stack-depth limit.
//
// A skill file <name>.js looks like:
//   // name: hello
//   // description: Say hello
//   function run(kairos, args) { return "echo:" + kairos.ask_llm("hi"); }
package org.kairos.agent.skills

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runBlocking
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.*
import org.mozilla.javascript.BaseFunction
import org.mozilla.javascript.Context
import org.mozilla.javascript.ContextFactory
import org.mozilla.javascript.RhinoException
import org.mozilla.javascript.Scriptable
import org.mozilla.javascript.ScriptableObject
import java.io.File

/** Whitelisted engine methods (desktop runner.ALLOWED_METHODS). Capabilities are enforced by the host. */
val ALLOWED_METHODS = setOf("ask_llm", "search_web", "scrape_page", "learn_from_page", "add_memory", "recall")

interface SkillHost {
    suspend fun askLlm(prompt: String): String
    suspend fun searchWeb(query: String, maxResults: Int): JsonElement
    suspend fun scrapePage(url: String): JsonElement
    suspend fun learnFromPage(url: String): JsonElement
    suspend fun addMemory(content: String): Boolean
    suspend fun recall(query: String, limit: Int): JsonElement
}

class SkillError(msg: String) : RuntimeException(msg)

data class SkillInfo(val name: String, val description: String)

private val SAFE_ID = Regex("^[a-z0-9_]{1,40}$")
fun safeId(name: String?): Boolean = SAFE_ID.matches((name ?: "").trim())

/** base/<name>.js, guaranteed to stay inside base (desktop safety.confine_path). */
fun confinePath(base: File, name: String, ext: String = ".js"): File {
    if (!safeId(name)) throw IllegalArgumentException("Invalid name '$name': use lowercase letters, digits and _ only.")
    val b = base.canonicalFile
    val t = File(b, name.trim() + ext).canonicalFile
    if (t.parentFile != b) throw IllegalArgumentException("Path escapes the allowed directory.")
    return t
}

private class TimedContext(f: ContextFactory) : Context(f) { var deadline = Long.MAX_VALUE }

private object SandboxFactory : ContextFactory() {
    override fun makeContext(): Context = TimedContext(this).apply {
        @Suppress("DEPRECATION")
        optimizationLevel = -1 // interpreted: Android cannot load generated bytecode
        maximumInterpreterStackDepth = 2000
        instructionObserverThreshold = 10_000
        setClassShutter { false }
        languageVersion = Context.VERSION_ES6
    }
    override fun observeInstructionCount(cx: Context, instructionCount: Int) {
        if (System.currentTimeMillis() > (cx as TimedContext).deadline) throw SkillError("skill timed out")
    }
}

private const val PRELUDE = """
var kairos = (function (h) {
  function rpc(m, a) {
    var r = JSON.parse(String(h.call(m, JSON.stringify(a))));
    if (r.error !== undefined) throw new Error(r.error);
    return r.result;
  }
  return Object.freeze({
    ask_llm: function (prompt) { return rpc("ask_llm", { prompt: String(prompt) }); },
    search_web: function (query, max_results) { return rpc("search_web", { query: String(query), max_results: max_results || 10 }); },
    scrape_page: function (url) { return rpc("scrape_page", { url: String(url) }); },
    learn_from_page: function (url) { return rpc("learn_from_page", { url: String(url) }); },
    add_memory: function (content) { return rpc("add_memory", { content: String(content) }); },
    recall: function (query, limit) { return rpc("recall", { query: String(query), limit: limit || 8 }); },
    call: function (method, args) { return rpc(String(method), args || {}); }
  });
})(__host);
__host = undefined;
"""

class SkillSandbox(private val host: SkillHost, private val timeoutMs: Long = 30_000) {

    private fun dispatch(method: String, a: JsonObject): JsonElement = runBlocking {
        fun s(k: String) = a[k]?.jsonPrimitive?.contentOrNull.orEmpty()
        fun i(k: String, d: Int) = a[k]?.jsonPrimitive?.intOrNull ?: d
        when (method) {
            "ask_llm" -> JsonPrimitive(host.askLlm(s("prompt")))
            "search_web" -> host.searchWeb(s("query"), i("max_results", 10).coerceIn(1, 25))
            "scrape_page" -> host.scrapePage(s("url"))
            "learn_from_page" -> host.learnFromPage(s("url"))
            "add_memory" -> JsonPrimitive(host.addMemory(s("content")))
            "recall" -> host.recall(s("query"), i("limit", 8).coerceIn(1, 50))
            else -> throw SecurityException("method '$method' is not allowed")
        }
    }

    /** Runs `run(kairos, args)` from [source] and returns its result as a string. */
    suspend fun run(source: String, args: Map<String, String> = emptyMap(), fileName: String = "skill.js"): String =
        withContext(Dispatchers.IO) {
            val cx = SandboxFactory.enterContext() as TimedContext
            try {
                cx.deadline = System.currentTimeMillis() + timeoutMs
                val scope = cx.initSafeStandardObjects()
                val hostFn = object : BaseFunction() {
                    override fun call(c: Context, s: Scriptable, t: Scriptable?, fa: Array<out Any?>): Any {
                        val method = Context.toString(fa.getOrNull(0))
                        val out = try {
                            if (method !in ALLOWED_METHODS) throw SecurityException("method '$method' is not allowed")
                            if (System.currentTimeMillis() > (c as TimedContext).deadline) throw SkillError("skill timed out")
                            val a = Json.parseToJsonElement(Context.toString(fa.getOrNull(1))).jsonObject
                            buildJsonObject { put("result", dispatch(method, a)) }
                        } catch (e: SkillError) { throw e } catch (e: Exception) {
                            buildJsonObject { put("error", e.message ?: e.javaClass.simpleName) }
                        }
                        return out.toString()
                    }
                }
                val holder = cx.newObject(scope)
                ScriptableObject.putProperty(holder, "call", hostFn)
                ScriptableObject.putProperty(scope, "__host", holder)
                cx.evaluateString(scope, PRELUDE, "prelude.js", 1, null)
                cx.evaluateString(scope, source, fileName, 1, null)
                val fn = ScriptableObject.getProperty(scope, "run") as? org.mozilla.javascript.Function
                    ?: throw SkillError("no run(kairos, args) function found")
                val jsArgs = cx.evaluateString(scope, "JSON.parse(" + JsonPrimitive(
                    JsonObject(args.mapValues { JsonPrimitive(it.value) }).toString()).toString() + ")", "args.js", 1, null)
                val kairos = ScriptableObject.getProperty(scope, "kairos")
                val r = fn.call(cx, scope, scope, arrayOf(kairos, jsArgs))
                when (r) {
                    null, org.mozilla.javascript.Undefined.instance -> ""
                    is Scriptable -> Context.toString(cx.evaluateString(scope, "(function(v){return typeof v==='string'?v:JSON.stringify(v);})", "fmt.js", 1, null)
                        .let { (it as org.mozilla.javascript.Function).call(cx, scope, scope, arrayOf(r)) })
                    else -> Context.toString(r)
                }
            } catch (e: SkillError) { throw e
            } catch (e: RhinoException) {
                val msg = e.details() ?: e.message
                throw SkillError(if (msg?.contains("skill timed out") == true) "skill timed out" else "skill error: $msg (line ${e.lineNumber()})")
            } catch (e: StackOverflowError) { throw SkillError("skill error: stack too deep")
            } finally { Context.exit() }
        }
}

/** Skills on disk (desktop SkillManager). */
class SkillManager(val dir: File, private val sandbox: SkillSandbox) {
    init { dir.mkdirs() }

    fun listFiles(): List<File> = dir.listFiles { f -> f.isFile && f.name.endsWith(".js") && !f.name.startsWith("_") }
        ?.sortedBy { it.name }.orEmpty()

    fun listSkills(): List<SkillInfo> = listFiles().map { f ->
        val meta = meta(f.readText())
        SkillInfo(f.nameWithoutExtension, meta["description"].orEmpty())
    }

    fun exists(name: String) = safeId(name) && confinePath(dir, name).isFile

    fun readSource(name: String): String = try {
        confinePath(dir, name).let { if (it.isFile) it.readText() else "" }
    } catch (e: IllegalArgumentException) { "" }

    fun saveSource(name: String, code: String): File = confinePath(dir, name).also { it.writeText(code) }
    fun createSkill(name: String, code: String): File = saveSource(name, code)
    fun deleteSkill(name: String): Boolean = confinePath(dir, name).let { it.isFile && it.delete() }

    suspend fun runSkill(name: String, args: Map<String, String> = emptyMap()): String {
        val f = confinePath(dir, name)
        if (!f.isFile) throw SkillError("Skill '$name' not found.")
        return sandbox.run(f.readText(), args, f.name)
    }

    companion object {
        fun meta(source: String): Map<String, String> = source.lineSequence().take(20)
            .mapNotNull { Regex("^\\s*//\\s*(name|description)\\s*:\\s*(.*)$").find(it) }
            .associate { it.groupValues[1] to it.groupValues[2].trim() }

        fun template(name: String, description: String) = """// name: $name
// description: ${description.replace('\n', ' ')}
// Generated skill. `kairos` offers: ask_llm(prompt), search_web(query, max), scrape_page(url),
// learn_from_page(url), add_memory(text), recall(query, limit). `args` holds string arguments.
function run(kairos, args) {
  // TODO: implement skill logic here
  return "Skill $name executed.";
}
"""

        fun generationPrompt(name: String, description: String) =
            "Write a complete KAIROS skill in JavaScript (ES5/ES6, no modules, no require, no fetch, no timers).\n" +
            "Skill name (lowercase, underscores): $name\nSkill description: $description\n\nRequirements:\n" +
            "- Start with the header lines `// name: $name` and `// description: <one line>`.\n" +
            "- Define `function run(kairos, args)` that performs the described task and returns a string.\n" +
            "- `args` is an object of string arguments. `kairos` provides synchronous functions: ask_llm(prompt) -> string, " +
            "search_web(query, max_results) -> [{title,url,description}], scrape_page(url) -> {title,text}, " +
            "learn_from_page(url) -> {title,summary}, add_memory(text) -> bool, recall(query, limit) -> [string].\n" +
            "- There is no other I/O: no files, network, Java or Android APIs.\nOutput ONLY the code, no markdown fences."

        fun stripCodeFences(code: String): String {
            var lines = code.trim().lines()
            if (lines.firstOrNull()?.startsWith("```") == true) lines = lines.drop(1)
            if (lines.lastOrNull()?.trim() == "```") lines = lines.dropLast(1)
            return lines.joinToString("\n").trim()
        }

        fun looksValid(code: String) = Regex("function\\s+run\\s*\\(").containsMatchIn(code)
    }
}
